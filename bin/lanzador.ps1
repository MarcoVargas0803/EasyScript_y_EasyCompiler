# lanzador.ps1 - Compila (si hace falta) y ejecuta EasyCompiler.
#
# Se invoca desde easy.cmd, que es lo que queda en el PATH:
#
#   easy Tests\codigo1.easy                       Analiza (solo errores)
#   easy Tests\codigo1.easy --arbol-sintactico    Ademas el arbol sintactico
#   easy Tests\codigo1.easy --arbol-sintactico-completo
#   easy Tests\codigo1.easy --tabla-simbolos --codigo-intermedio
#   easy --compilar                               Solo compila, siempre
#   easy --compilar Tests\codigo1.easy ...        Fuerza la compilacion y analiza
#
# Las banderas pasan tal cual a frontend.Main, que es quien las interpreta.
#
# Por debajo hace los mismos 4 pasos del README:
#
#   jjtree  backend\EasyCompiler.jjt  ->  backend\EasyCompiler.jj + nodos del arbol
#   javacc  backend\EasyCompiler.jj   ->  analizador lexico y sintactico
#   javac   backend\*.java frontend\*.java  ->  out\
#   java    frontend.Main <archivo> <banderas>
#
# Los tres primeros solo se repiten si cambio algo: si backend\EasyCompiler.jjt o
# algun .java escrito a mano es mas nuevo que la ultima compilacion
# (out\.compilado). La salida de jjtree/javacc/javac va a out\compilacion.log y
# solo se muestra si un paso falla.
#
# Usa rutas completas al JDK y a JavaCC: no depende de que java, javac, jjtree o
# javacc esten en el PATH.

$ErrorActionPreference = "Stop"

# Ruta al jar de JavaCC. Ajustala si cambias de equipo.
$JAVACC = "C:\javacc\javacc-javacc-7.0.13\target\javacc.jar"

# JDK a usar. Se prefiere el que declara el proyecto en .idea\misc.xml (openjdk-21)
# para que la terminal y IntelliJ compilen con la misma version; los demas son
# respaldo. Si ya tienes JAVA_HOME configurado, ese gana.
$JDKS = @(
    $env:JAVA_HOME,
    "C:\Users\carme\.jdks\openjdk-21.0.2",
    "C:\Program Files\Java\jdk-22",
    "C:\Program Files\Java\jdk-24"
)

$java = $null
foreach ($base in $JDKS) {
    if ([string]::IsNullOrWhiteSpace($base)) { continue }
    $candidato = Join-Path $base "bin\java.exe"
    if (Test-Path $candidato) { $java = $candidato; $JDK = Join-Path $base "bin"; break }
}

if (-not $java) {
    Write-Host "No se encontro ningun JDK. Define JAVA_HOME o edita `$JDKS al inicio de bin\lanzador.ps1." -ForegroundColor Red
    exit 1
}

$javac = Join-Path $JDK "javac.exe"

foreach ($ruta in @($javac, $JAVACC)) {
    if (-not (Test-Path $ruta)) {
        Write-Host "No se encontro: $ruta`nRevisa las rutas al inicio de bin\lanzador.ps1." -ForegroundColor Red
        exit 1
    }
}

# bin\ esta dentro de la carpeta del proyecto.
$proyecto = Split-Path $PSScriptRoot -Parent
$out      = Join-Path $proyecto "out"
$sello    = Join-Path $out ".compilado"
$bitacora = Join-Path $out "compilacion.log"

# ---------------------------------------------------------------------------
# Argumentos: --compilar solo se reconoce al principio; todo lo demas es para Main.
# ---------------------------------------------------------------------------
$argumentos = @($args)
$forzar = $false
if ($argumentos.Count -gt 0 -and $argumentos[0] -eq "--compilar") {
    $forzar = $true
    $argumentos = @($argumentos | Select-Object -Skip 1)
}

# ---------------------------------------------------------------------------
# Hay que compilar si se pidio, si nunca se ha compilado, o si alguna fuente
# escrita a mano es mas nueva que la ultima compilacion. Los .java generados por
# JJTree/JavaCC no cuentan: se reconocen por su cabecera "Generated By:".
# ---------------------------------------------------------------------------
function Hace-FaltaCompilar {
    if (-not (Test-Path $sello)) { return $true }
    $ultima = (Get-Item $sello).LastWriteTime

    $fuentes = @(Get-Item (Join-Path $proyecto "backend\EasyCompiler.jjt"))
    $fuentes += Get-ChildItem (Join-Path $proyecto "backend") -Filter *.java -File
    $fuentes += Get-ChildItem (Join-Path $proyecto "frontend") -Filter *.java -File

    foreach ($f in $fuentes) {
        if ($f.LastWriteTime -le $ultima) { continue }
        $cabecera = (Get-Content -LiteralPath $f.FullName -TotalCount 2) -join "`n"
        if ($cabecera -notmatch "Generated By:") { return $true }
    }
    return $false
}

# Ejecuta un paso de la compilacion con su salida a la bitacora. Devuelve true
# si termino bien. Se usa Start-Process para que lo que java escribe en stderr no
# se convierta en error de PowerShell (Windows PowerShell 5.1 lo haria).
function Paso([string] $nombre, [string] $exe, [string] $argumentosPaso) {
    $salida = Join-Path $out "paso.out.tmp"
    $errores = Join-Path $out "paso.err.tmp"
    $p = Start-Process -FilePath $exe -ArgumentList $argumentosPaso -WorkingDirectory $proyecto `
        -NoNewWindow -Wait -PassThru -RedirectStandardOutput $salida -RedirectStandardError $errores
    Add-Content -LiteralPath $bitacora -Value ("== " + $nombre + " ==")
    Get-Content -LiteralPath $salida, $errores | Add-Content -LiteralPath $bitacora
    Remove-Item -LiteralPath $salida, $errores
    return ($p.ExitCode -eq 0)
}

function Compilar {
    New-Item -ItemType Directory -Force $out | Out-Null
    if (Test-Path $sello) { Remove-Item -LiteralPath $sello }
    Set-Content -LiteralPath $bitacora -Value ("Compilacion " + (Get-Date))

    Write-Host "Compilando EasyCompiler... " -NoNewline -ForegroundColor DarkGray

    $pasos = @(
        @("jjtree", $java,  "-cp `"$JAVACC`" jjtree -OUTPUT_DIRECTORY:backend backend\EasyCompiler.jjt"),
        @("javacc", $java,  "-cp `"$JAVACC`" javacc -OUTPUT_DIRECTORY:backend backend\EasyCompiler.jj"),
        @("javac",  $javac, "-encoding UTF-8 -d out backend\*.java frontend\*.java")
    )
    foreach ($paso in $pasos) {
        if (-not (Paso $paso[0] $paso[1] $paso[2])) {
            Write-Host "fallo en $($paso[0])." -ForegroundColor Red
            Write-Host ""
            Get-Content -LiteralPath $bitacora | Write-Host
            return $false
        }
    }

    Set-Content -LiteralPath $sello -Value (Get-Date)
    Write-Host "listo." -ForegroundColor DarkGray
    return $true
}

if ($forzar -or (Hace-FaltaCompilar)) {
    if (-not (Compilar)) { exit 1 }
}

# easy --compilar sin archivo: solo se queria compilar.
if ($forzar -and $argumentos.Count -eq 0) { exit 0 }

# ---------------------------------------------------------------------------
# Ejecutar desde la carpeta donde esta el usuario, para que las rutas relativas
# del archivo funcionen igual que con cualquier otro compilador.
# ---------------------------------------------------------------------------
& $java "-Dfile.encoding=UTF-8" -cp $out frontend.Main @argumentos
exit $LASTEXITCODE
